from __future__ import annotations

import json

from patent_troll.models import LEGAL_DISCLAIMER, PatentabilityWorkflowResult


def render_json(result: PatentabilityWorkflowResult) -> str:
    return json.dumps(result.to_dict(), indent=2)


def render_markdown(result: PatentabilityWorkflowResult) -> str:
    analysis = result.analysis
    lines = [
        f"# Patentability Report: {result.idea.title}",
        "",
        f"> {LEGAL_DISCLAIMER}",
        "",
        "## Scores",
        "",
        score_table(result),
        "",
        f"Generated by: `{analysis.generated_by}`",
        "",
        "## Summary",
        "",
        analysis.summary,
        "",
        "## Search Metadata",
        "",
        *search_metadata_lines(result),
        "",
        "## Prior Art",
        "",
    ]
    for item in result.prior_art:
        link = f" ({item.link})" if item.link else ""
        lines.append(f"- [{item.source}] {item.title} - similarity {item.similarity_score:.2f}{link}")
    lines.extend(["", "## Closest Overlaps", ""])
    for item in analysis.overlaps:
        lines.append(f"- {item.title}: {item.overlap} Risk: {item.risk}.")
    lines.extend(["", "## Section 101 Flags", ""])
    for item in analysis.section_101_flags:
        lines.append(f"- {item.flag}: {item.detail}")
    lines.extend(["", "## Suggested Technical Tweaks", ""])
    for item in analysis.suggested_tweaks:
        lines.append(f"- {item.title}: {item.detail}")
    return "\n".join(lines).strip() + "\n"


def render_github_markdown(result: PatentabilityWorkflowResult) -> str:
    analysis = result.analysis
    lines = [
        f"## Patentability Snapshot: {result.idea.title}",
        "",
        f"> {LEGAL_DISCLAIMER}",
        "",
        score_table(result),
        "",
        f"Generated by: `{analysis.generated_by}`",
        "",
        "**Search provenance**",
        "",
        *compact_search_metadata_lines(result),
        "",
        "**Top overlaps**",
        "",
    ]
    for item in analysis.overlaps[:3]:
        lines.append(f"- **{item.risk}** - {item.title}: {item.overlap}")
    if not analysis.overlaps:
        lines.append("- No overlaps reported.")
    lines.extend(["", "**Suggested technical tweaks**", ""])
    for item in analysis.suggested_tweaks[:3]:
        lines.append(f"- **{item.title}:** {item.detail}")
    if not analysis.suggested_tweaks:
        lines.append("- No technical tweaks reported.")
    lines.extend(
        [
            "",
            "<sub>Scores are product signals for invention-disclosure review, not legal conclusions.</sub>",
        ]
    )
    return "\n".join(lines).strip() + "\n"


def score_table(result: PatentabilityWorkflowResult) -> str:
    analysis = result.analysis
    return "\n".join(
        [
            "| Signal | Score | Meaning |",
            "| --- | ---: | --- |",
            f"| Novelty | {analysis.novelty_score}/100 | {score_meaning(analysis.novelty_score, positive=True)} |",
            f"| Obviousness risk | {analysis.obviousness_risk}/100 | {score_meaning(analysis.obviousness_risk, positive=False)} |",
            f"| Section 101 eligibility risk | {analysis.eligibility_risk}/100 | {score_meaning(analysis.eligibility_risk, positive=False)} |",
        ]
    )


def search_metadata_lines(result: PatentabilityWorkflowResult) -> list[str]:
    metadata = result.search_metadata
    if not metadata:
        return ["- Search metadata unavailable."]
    lines = [
        f"- Query: `{metadata.query}`",
        f"- Demo fallback used: {'yes' if metadata.demo_fallback_used else 'no'}",
        f"- Returned results: {metadata.returned_count}",
    ]
    for provider in metadata.providers:
        lines.append(f"- {provider.provider}: {provider.status}, {provider.result_count} result(s). {provider.message}")
    return lines


def compact_search_metadata_lines(result: PatentabilityWorkflowResult) -> list[str]:
    metadata = result.search_metadata
    if not metadata:
        return ["- Search metadata unavailable."]
    providers = ", ".join(
        f"{provider.provider}: {provider.status} ({provider.result_count})" for provider in metadata.providers
    )
    return [
        f"- Demo fallback used: {'yes' if metadata.demo_fallback_used else 'no'}",
        f"- Returned results: {metadata.returned_count}",
        f"- Providers: {providers}",
    ]


def score_meaning(score: int, positive: bool) -> str:
    if positive:
        if score >= 70:
            return "stronger novelty signal"
        if score >= 45:
            return "mixed novelty signal"
        return "weak novelty signal"
    if score >= 70:
        return "high risk"
    if score >= 40:
        return "medium risk"
    return "lower risk"
